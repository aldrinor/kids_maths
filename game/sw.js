const SHELL_CACHE = "km-shell-" + VERSION, RUNTIME_CACHE = "km-runtime", VOICE_CACHE = "km-voice";
const READY_URL = "__km_ready", VOICE_KEEP = 2500;
const here = new URL("./", self.location.href);
const abs = rel => new URL(rel, here).href;

self.addEventListener("install", event => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await cache.addAll(FILES.map(abs));                                       // the shell: all or nothing
    await Promise.all(ART.map(async rel => { try { await cache.add(abs(rel)); } catch (e) { /* one picture may fail; it is saved when first used */ } }));
    await cache.put(abs(READY_URL), new Response("ready", { headers: { "content-type": "text/plain" } }));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith("km-shell-") && k !== SHELL_CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

const isVoiceClip = url => url.origin === self.location.origin && /\/voice\/[0-9a-f]{8}\.mp3$/.test(url.pathname);
async function findSaved(request, navigate) {
  const opts = navigate ? { ignoreSearch: true } : undefined;
  return (await caches.match(request, opts)) || (navigate ? await caches.match(abs("index.html"), { ignoreSearch: true }) : undefined);
}
async function keepNewest(cache, max) {
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - max; i++) await cache.delete(keys[i]);
}

async function voiceFirst(request) {
  const cache = await caches.open(VOICE_CACHE), saved = await cache.match(request);
  if (saved) return saved;
  const res = await fetch(request);
  if (res && res.status === 200) { try { await cache.put(request, res.clone()); await keepNewest(cache, VOICE_KEEP); } catch (e) {} }
  return res;
}

/* pages, scripts and styles: the fresh copy first (so a fix reaches the child at once), the saved copy only when the network is slow (4 s) or gone */
function networkFirst(event, request, navigate) {
  const fresh = fetch(request).then(async res => {
    if (res && res.status === 200) { const c = await caches.open(RUNTIME_CACHE); await c.put(request, res.clone()); }
    return res;
  });
  event.waitUntil(fresh.catch(() => {}));
  const slow = new Promise(resolve => setTimeout(resolve, 4000)).then(() => findSaved(request, navigate)).then(saved => saved || fresh);
  return Promise.race([fresh.catch(() => null), slow]).then(res => res || findSaved(request, navigate)).then(res => res || fresh.catch(() => Response.error()));
}

function staleWhileRevalidate(event, request, navigate) {
  const fresh = fetch(request).then(async res => {
    if (res && (res.status === 200 || res.type === "opaque")) { const c = await caches.open(RUNTIME_CACHE); await c.put(request, res.clone()); }
    return res;
  });
  event.waitUntil(fresh.catch(() => {}));                                      // the refresh finishes even after the page has its answer
  return findSaved(request, navigate).then(saved => saved || fresh.catch(() => Response.error()));
}

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET" || request.headers.has("range")) return;       // audio range requests go straight to the network
  const url = new URL(request.url);
  if (isVoiceClip(url)) { event.respondWith(voiceFirst(request).catch(() => Response.error())); return; }
  const sameOrigin = url.origin === self.location.origin;
  const fontsHost = /(^|\.)(fonts\.googleapis\.com|fonts\.gstatic\.com)$/.test(url.hostname);
  if (!sameOrigin && !fontsHost) return;
  if (sameOrigin && !url.pathname.startsWith(here.pathname) && !/\/(modules|topics)\//.test(url.pathname)) return;   // only this game's own files
  const isCode = request.mode === "navigate" || /\.(html|js|css|json|webmanifest)$/.test(url.pathname);
  event.respondWith(isCode ? networkFirst(event, request, request.mode === "navigate") : staleWhileRevalidate(event, request, request.mode === "navigate"));
});
